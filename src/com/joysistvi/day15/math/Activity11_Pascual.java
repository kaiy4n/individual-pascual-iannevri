package com.joysistvi.day15.math;

public class Activity11_Pascual {

    public static void main(String[] args) {

        // Math.abs() → absolute value
        // - returns the absolute (positive) value of different numbers.
        System.out.println("Math.abs()");
        System.out.println(Math.abs(-6.7));
        System.out.println(Math.abs(-5));
        System.out.println();

        // Math.max() → maximum of two values
        // - get the highest value from different pairs of numbers.
        System.out.println("Math.max()");
        System.out.println(Math.max(55, 34));
        System.out.println(Math.max(-3.2, -1.1));
        System.out.println();

        // Math.min() → minimum of two values
        // - get the smallest value from different pairs of numbers.
        System.out.println("Math.min()");
        System.out.println(Math.min(78, 90));
        System.out.println(Math.min(-333, -999));
        System.out.println();

        // Math.pow() → power (exponentiation)
        // - raise different numbers to different powers.
        System.out.println("Math.pow()");
        System.out.println(Math.pow(2, 4));
        System.out.println(Math.pow(-5, 2));
        System.out.println(Math.pow(3, -1));
        System.out.println();

        // Math.sqrt() → square root
        // - return the square root of different numbers.
        System.out.println("Math.sqrt()");
        System.out.println(Math.sqrt(16));
        System.out.println(Math.sqrt(125));
        System.out.println();

        // Math.round() → round to nearest integer
        // - rounds a number to the nearest integer
        System.out.println("Math.round()");
        System.out.println(Math.round(5.6));
        System.out.println(Math.round(5.3));
        System.out.println(Math.round(50.00678));
        System.out.println();

        // Math.ceil() → round up (ceiling)
        // - round numbers up to the nearest integer
        System.out.println("Math.ceil()");
        System.out.println(Math.ceil(5.6));
        System.out.println(Math.ceil(5.3));
        System.out.println(Math.ceil(50.00678));
        System.out.println();

        // Math.floor() → round down (floor)
        // - round numbers down to the nearest integer
        System.out.println("Math.floor()");
        System.out.println(Math.floor(5.6));
        System.out.println(Math.floor(5.3));
        System.out.println(Math.floor(50.00678));
        System.out.println();

        // Math.random() → random number between 0.0 and 1.0
        // - generate a random number
        System.out.println("Math.random()");
        System.out.println(Math.random());
        System.out.println();

        // Math.log() → natural logarithm (base e)
        // - return the natural logarithm of different numbers
        System.out.println("Math.log()");
        System.out.println(Math.log(1));
        System.out.println(Math.log(-1));
        System.out.println();

        // Math.log10() → logarithm base 10
        // - return the base 10 logarithm for different numbers
        System.out.println("Math.log10()");
        System.out.println(Math.log10(1));
        System.out.println(Math.log10(-1));
        System.out.println();

        // Math.exp() → exponential function (e^x)
        // - Return e raised to the power of different numbers
        // - Euler's number (2.71828...)
        System.out.println("Math.exp()");
        System.out.println(Math.exp(1));
        System.out.println(Math.exp(2));
        System.out.println();

        // Math.sin() → sine of an angle (in radians)
        // - return the sine of different angles
        System.out.println("Math.sin()");
        System.out.println(Math.sin(1));
        System.out.println(Math.sin(2));
        System.out.println();

        // Math.cos() → cosine of an angle (in radians)
        // - return the cosine of different angles
        System.out.println("Math.cos()");
        System.out.println(Math.cos(3));
        System.out.println(Math.cos(-3));
        System.out.println();

        // Math.tan() → tangent of an angle (in radians)
        // - return the tangent of different angles
        System.out.println("Math.tan()");
        System.out.println(Math.tan(3));
        System.out.println(Math.tan(-3));
        System.out.println();
        
    }

}
